"""Emotion engine models for Aevum Core.

Represents the structured result of an EmotionEngine orchestration cycle.

Guarantees:
- Immutable domain representation (frozen=True, extra="forbid").
- Transparent traceability: encapsulates both the evaluated transition proposal
  and the resulting authoritative state application.
"""

from pydantic import BaseModel, ConfigDict, Field

from app.emotion.application_models import EmotionStateApplicationResult
from app.emotion.transition_models import EmotionTransitionProposal


class EmotionEngineResult(BaseModel):
    """Immutable domain representation of an EmotionEngine orchestration cycle result."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    proposal: EmotionTransitionProposal = Field(
        ...,
        description="The transition proposal generated by EmotionTransitionEvaluator.",
    )
    application_result: EmotionStateApplicationResult = Field(
        ...,
        description="The authoritative state application result from EmotionStateApplicationService.",
    )
